"""Emit HLSL global-constant declarations that reproduce a blob's $Globals layout.

    .venv\\Scripts\\python.exe shaders\\tools\\gen_globals.py --asm X.asm --out decls.fxh
        [--cbuffer $Globals] [--select fc|vc|all] [--alias-header H.fxh ...] [--no-pin]

Reads the reflection header of an fxc /dumpbin disassembly and writes one
declaration per declared variable (used or not), in reflection (= declaration)
order, each pinned with register(c<offset/16>) so the offsets come out exactly
as in the vanilla blob regardless of how fxc would pack unpinned scalars.

--select fc   only variables that are not vertex constants (names not starting
              with gVC_ / VR_)
--select vc   only vertex constants
--alias-header  header(s) containing '#define <public> <reflected>' aliases
              (e.g. a register-name alias). When a reflected name has an alias,
              the alias #define is emitted and the declaration uses the public
              name, so the reflected name is reproduced through the macro.

The output contains only identifiers, types and register numbers taken from the
reflection data; no shader source text is embedded in this tool.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fxcasm  # noqa: E402

ALIAS_RE = re.compile(r"#define\s+(g[A-Z]{2}_\w+)\s+((?:DL_FREG|VR)_\w+)\b")


def load_aliases(paths):
    rev = {}
    for p in paths or []:
        with open(p, encoding="utf-8", errors="replace") as fh:
            for ln in fh:
                m = ALIAS_RE.search(ln)
                if m:
                    rev.setdefault(m.group(2), m.group(1))
    return rev


def is_vc(name):
    return name.startswith(("gVC_", "VR_"))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--asm", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cbuffer", default="$Globals")
    ap.add_argument("--select", choices=("fc", "vc", "all"), default="all")
    ap.add_argument("--alias-header", nargs="*")
    ap.add_argument("--no-pin", action="store_true")
    ap.add_argument("--guard", default=None)
    a = ap.parse_args()

    si = fxcasm.parse_asm(open(a.asm, encoding="utf-8", errors="replace").read())
    cb = next((c for c in si.cbuffers if c.name == a.cbuffer), None)
    if cb is None:
        print("cbuffer not found"); return 1
    rev = load_aliases(a.alias_header)
    out = [f"// generated by shaders/tools/gen_globals.py from {os.path.basename(a.asm)} ({a.cbuffer}, select={a.select})"]
    if a.guard:
        out += [f"#ifndef {a.guard}", f"#define {a.guard}"]
    n = 0
    for v in cb.vars:
        if a.select == "fc" and is_vc(v.name): continue
        if a.select == "vc" and not is_vc(v.name): continue
        m = re.match(r"^([\w$]+)(\[\d+\])?$", v.name)
        base, arr = m.group(1), m.group(2) or ""
        if v.offset % 16:
            print(f"warning: {v.name} offset {v.offset} not register aligned; pinned to c{v.offset // 16}", file=sys.stderr)
        reg = "" if a.no_pin else f" : register(c{v.offset // 16})"
        pub = rev.get(base)
        if pub:
            out.append(f"\t#define {pub} {base}")
            out.append(f"\tuniform {v.type} {pub}{arr}{reg};")
        else:
            out.append(f"\tuniform {v.type} {base}{arr}{reg};")
        n += 1
    if a.guard:
        out.append(f"#endif // {a.guard}")
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {n} declarations -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
