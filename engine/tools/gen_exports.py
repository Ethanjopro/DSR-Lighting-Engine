#!/usr/bin/env python3
"""Generate the d3d11.dll proxy's export list from the system DLL.

Every export forwards to the real DLL through a MASM thunk, except the two device-creation
entry points, which proxy.cpp implements. Run this once; the output is committed because the
export set is stable and the build should not depend on the machine's System32 contents.
"""
import pathlib
import re
import subprocess
import sys

HOOKED = {"D3D11CreateDevice", "D3D11CreateDeviceAndSwapChain"}


def exports(dumpbin: str) -> list[str]:
    out = subprocess.run(
        [dumpbin, "/nologo", "/exports", r"C:\Windows\System32\d3d11.dll"],
        capture_output=True, text=True, check=True,
    ).stdout
    return re.findall(r"^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\w+)\s*$", out, re.M)


def main() -> int:
    dumpbin, src = sys.argv[1], pathlib.Path(sys.argv[2])
    names = exports(dumpbin)
    if "D3D11CreateDevice" not in names:
        raise SystemExit("export parse failed")

    d = ["LIBRARY d3d11", "EXPORTS"]
    for n in names:
        d.append(f"    {n}=hook_{n}" if n in HOOKED else f"    {n}=thunk_{n}")
    (src / "exports.def").write_text("\n".join(d) + "\n", encoding="ascii")

    a = [
        "; Generated by engine/tools/gen_exports.py. Forwards every unhooked d3d11.dll export.",
        "EXTERN g_real_table:QWORD",
        "EXTERN ensure_real:PROC",
        ".code",
    ]
    for i, n in enumerate(names):
        if n in HOOKED:
            continue
        a += [
            f"thunk_{n} PROC",
            f"    mov rax, QWORD PTR g_real_table[{i * 8}]",
            "    test rax, rax",
            f"    jnz go_{i}",
            "    push rcx",
            "    push rdx",
            "    push r8",
            "    push r9",
            "    sub rsp, 28h",
            "    call ensure_real",
            "    add rsp, 28h",
            "    pop r9",
            "    pop r8",
            "    pop rdx",
            "    pop rcx",
            f"    mov rax, QWORD PTR g_real_table[{i * 8}]",
            f"go_{i}:",
            "    jmp rax",
            f"thunk_{n} ENDP",
        ]
    a.append("END")
    (src / "exports.asm").write_text("\n".join(a) + "\n", encoding="ascii")

    t = ["// Generated by engine/tools/gen_exports.py.", f"#define DSRLE_NUM_EXPORTS {len(names)}",
         "static const char* const kExportNames[DSRLE_NUM_EXPORTS] = {"]
    t += [f'    "{n}",' for n in names]
    t.append("};")
    (src / "exports_table.inc").write_text("\n".join(t) + "\n", encoding="ascii")
    print(f"{len(names)} exports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
