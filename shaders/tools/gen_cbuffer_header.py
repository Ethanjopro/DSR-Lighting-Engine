"""Emit HLSL global-variable declarations that reproduce a cbuffer layout
recorded in a disassembly's reflection header.

    .venv\\Scripts\\python.exe shaders\\tools\\gen_cbuffer_header.py ASM [options] > out.fxh

The reflection lists every declared variable of the cbuffer (used or not) with
type, name, offset and size.  Each variable is emitted in reflection order as

    <type> <name> : register(c<offset/16>);     (pinned part)
    <type> <name>;                              (unpinned part, see --unpinned-from)

Options
    --cbuffer NAME        cbuffer to read (default $Globals)
    --unpinned-from NAME  first variable that is emitted without a register()
                          binding (everything after it is unpinned as well)
    --stop-at NAME        stop before this variable (exclusive)
    --start-at NAME       start at this variable (inclusive)
    --alias-from FILE     (repeatable) read '#define <alias> <name>' lines from FILE and emit
                          '#define <alias> <name>' before each declaration whose
                          name has such an alias (keeps code-side names working
                          when the reflection names differ)
    --reg-macro M         wrap the register in a macro, e.g. FC_REG -> ': FC_REG(c84)'
    --guard NAME          wrap the output in an include guard

Generic tool: it reads only what the reflection header states.
"""
from __future__ import annotations

import argparse
import re
import sys

VAR_RE = re.compile(r"^//\s+(?P<type>(?:row_major\s+|column_major\s+)?\w+)\s+(?P<name>[\w$]+)(?P<arr>\[\d+\])?;\s*//\s*Offset:\s*(?P<off>\d+)\s+Size:\s*(?P<size>\d+)")


def read_vars(asm_path: str, cbname: str):
    out = []
    cur = None
    with open(asm_path, encoding="utf-8", errors="replace") as fh:
        for ln in fh:
            m = re.match(r"^//\s*cbuffer\s+([\w$]+)", ln)
            if m:
                cur = m.group(1)
                continue
            if cur is None:
                continue
            if re.match(r"^//\s*}\s*$", ln):
                if cur == cbname and out:
                    break
                cur = None
                continue
            if cur != cbname:
                continue
            m = VAR_RE.match(ln)
            if m:
                out.append(dict(type=m.group("type"), name=m.group("name"), arr=m.group("arr") or "",
                                off=int(m.group("off")), size=int(m.group("size"))))
    return out


def read_aliases(path: str) -> dict:
    al = {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for ln in fh:
            m = re.match(r"^\s*#define\s+(\w+)\s+(\w+)\s*(?://.*)?$", ln)
            if m:
                al.setdefault(m.group(2), []).append(m.group(1))
    return al


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("asm")
    ap.add_argument("--cbuffer", default="$Globals")
    ap.add_argument("--unpinned-from")
    ap.add_argument("--start-at")
    ap.add_argument("--stop-at")
    ap.add_argument("--alias-from", action="append", default=[])
    ap.add_argument("--reg-macro")
    ap.add_argument("--guard")
    ap.add_argument("-o", "--out")
    a = ap.parse_args()

    vs = read_vars(a.asm, a.cbuffer)
    if not vs:
        print(f"no variables found for cbuffer {a.cbuffer}", file=sys.stderr)
        return 1
    aliases = {}
    for f in a.alias_from:  # later files add aliases; duplicates are dropped
        for k, v in read_aliases(f).items():
            for al in v:
                if al not in aliases.setdefault(k, []):
                    aliases[k].append(al)
    lines = []
    if a.guard:
        lines += [f"#ifndef {a.guard}", f"#define {a.guard}", ""]
    lines.append(f"// generated by gen_cbuffer_header.py from the reflection of {a.asm.replace(chr(92), '/').split('/')[-1]} ({a.cbuffer})")
    started = a.start_at is None
    pinned = True
    for v in vs:
        if not started:
            if v["name"] == a.start_at:
                started = True
            else:
                continue
        if a.stop_at and v["name"] == a.stop_at:
            break
        if a.unpinned_from and v["name"] == a.unpinned_from:
            pinned = False
        for al in aliases.get(v["name"], []):
            lines.append(f"#define {al} {v['name']}")
        decl = f"{v['type']} {v['name']}{v['arr']}"
        if pinned:
            reg = f"c{v['off'] // 16}"
            if v["off"] % 16:
                decl += f" : packoffset(c{v['off'] // 16}.{'xyzw'[(v['off'] % 16) // 4]})"
            elif a.reg_macro:
                decl += f" : {a.reg_macro}({reg})"
            else:
                decl += f" : register({reg})"
        lines.append(decl + ";")
    if a.guard:
        lines += ["", f"#endif // {a.guard}"]
    txt = "\n".join(lines) + "\n"
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(txt)
    else:
        sys.stdout.write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
