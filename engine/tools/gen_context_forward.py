#!/usr/bin/env python3
"""Generate forwarders for every ID3D11DeviceContext method from the Windows SDK header.

context.cpp hand-writes the methods listed in INTERCEPTED; the rest forward straight to the real
context. Run this when INTERCEPTED changes. The output is committed.
"""
import pathlib
import re
import sys

INTERCEPTED = {
    "Draw", "DrawIndexed", "DrawInstanced", "DrawIndexedInstanced", "DrawAuto",
    "DrawIndexedInstancedIndirect", "DrawInstancedIndirect", "Dispatch", "DispatchIndirect",
    "Map", "Unmap", "UpdateSubresource", "CopyResource", "CopySubresourceRegion", "ResolveSubresource",
    "ClearRenderTargetView", "ClearDepthStencilView", "GenerateMips", "ClearState",
    "ExecuteCommandList", "FinishCommandList", "CSSetShader", "PSSetShader", "VSSetConstantBuffers",
    "PSSetConstantBuffers", "VSSetShader", "OMSetRenderTargets", "OMSetRenderTargetsAndUnorderedAccessViews", "OMSetBlendState",
}

HEADER = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\um\d3d11.h")


def strip_annotations(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    out, i = [], 0
    while i < len(text):
        m = re.compile(r"\b_[A-Z][A-Za-z_]*\b").match(text, i)
        if m:
            i = m.end()
            j = i
            while j < len(text) and text[j] in " \t\r\n":
                j += 1
            if j < len(text) and text[j] == "(":
                depth, j = 1, j + 1
                while depth:
                    depth += {"(": 1, ")": -1}.get(text[j], 0)
                    j += 1
                i = j
            continue
        out.append(text[i])
        i += 1
    return "".join(out)


def split_params(params: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for ch in params:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [" ".join(p.split()) for p in parts]


def main() -> int:
    text = HEADER.read_text(encoding="utf8", errors="replace")
    start = text.index('MIDL_INTERFACE("c0bfa96c-e089-44fb-8eaf-26f8796190da")')
    end = text.index("};", start)
    body = strip_annotations(text[start:end])
    methods = re.findall(r"virtual\s+(\w+)\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*=\s*0\s*;", body, re.S)
    if len(methods) != 108:
        raise SystemExit(f"expected 108 ID3D11DeviceContext methods, parsed {len(methods)}")
    missing = INTERCEPTED - {m[1] for m in methods}
    if missing:
        raise SystemExit(f"unknown intercepted methods: {missing}")

    lines = ["// Generated by engine/tools/gen_context_forward.py from the Windows SDK d3d11.h."]
    for ret, name, params in methods:
        if name in INTERCEPTED:
            continue
        plist = split_params(params)
        args = []
        for p in plist:
            if p == "void":
                continue
            m = re.search(r"(\w+)\s*(\[.*\])?$", p)
            args.append(m.group(1))
        sig = ", ".join(p for p in plist if p != "void")
        call = f"real_->{name}({', '.join(args)})"
        lines.append(f"{ret} STDMETHODCALLTYPE {name}({sig}) override {{ {'return ' if ret != 'void' else ''}{call}; }}")
    pathlib.Path(sys.argv[1]).write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"{len(methods) - len(INTERCEPTED)} forwarders, {len(INTERCEPTED)} intercepted")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
